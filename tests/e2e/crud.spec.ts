test('crud: observation create → in_progress → close', async ({ page }) => {
  const errors = installResponseSpy(page)
  await signIn(page)
  await page.goto('/observations', { waitUntil: 'networkidle', timeout: 25_000 })

  const ok = await clickCreateOrSkip(page, 'observation')
  if (!ok) return

  const title = `Observation_${Date.now()}`
  // Try the most likely fields by accessible name; fall back to first text input.
  const titleField = page
    .getByLabel(/title|name|summary/i)
    .or(page.locator('input[type="text"]'))
    .first()
  await titleField.fill(title)

  // Optional description if present.
  const descField = page.getByLabel(/description|detail|note/i).first()
  if (await descField.count()) {
    try {
      await descField.fill(`Auto-generated by smoke @ ${new Date().toISOString()}`)
    } catch {}
  }

  // Submit
  const submit = page.getByRole('button', { name: /save|create|submit/i }).first()
  await submit.click()
  await page.waitForLoadState('networkidle', { timeout: 15_000 }).catch(() => {})

  // Assert it appears in the list (return to list page if not already there).
  if (!page.url().endsWith('/observations')) {
    // We may be on a detail page; navigate back.
    await page.goto('/observations', { waitUntil: 'networkidle', timeout: 15_000 })
  }
  await expect(page.getByText(title).first()).toBeVisible({ timeout: 10_000 })

  // Open it
  await page.getByText(title).first().click()
  await page.waitForLoadState('networkidle', { timeout: 10_000 }).catch(() => {})

  // Transition to in_progress
  const inProgressBtn = page
    .getByRole('button', { name: /in.?progress|start/i })
    .first()
  if (await inProgressBtn.count()) {
    await inProgressBtn.click().catch(() => {})
    await page.waitForLoadState('networkidle', { timeout: 5_000 }).catch(() => {})
  }

  // Close
  const closeBtn = page.getByRole('button', { name: /close|complete|resolve/i }).first()
  if (await closeBtn.count()) {
    await closeBtn.click().catch(() => {})
    await page.waitForLoadState('networkidle', { timeout: 5_000 }).catch(() => {})
  }

  await expectNoResponseErrors(errors)
})

