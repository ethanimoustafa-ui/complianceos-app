test('crud: invite team member', async ({ page }) => {
  // Specially treated: even if it 503s due to missing service-role key, we want
  // to assert the error body is *informative* rather than opaque.
  const inviteErrors: ResponseError[] = []
  const otherErrors: ResponseError[] = []

  page.on('response', async (r) => {
    const status = r.status()
    if (status < 400) return
    const url = r.url()
    if (url.includes('/_next/') || url.endsWith('/favicon.ico')) return
    let body: string | undefined
    try {
      body = (await r.text()).slice(0, 500)
    } catch {}
    if (/\/api\/team\/members\/invite/i.test(url)) {
      inviteErrors.push({ status, url, body })
    } else {
      otherErrors.push({ status, url, body })
    }
  })

  await signIn(page)
  await page.goto('/team/directory', { waitUntil: 'networkidle', timeout: 25_000 })

  const ok = await clickCreateOrSkip(page, 'invite')
  if (!ok) return

  const emailField = page.getByLabel(/email/i).or(page.locator('input[type="email"]')).first()
  await emailField.fill(`invitee_${Date.now()}@example.com`)

  // Some forms have a role select.
  const roleSelect = page.getByLabel(/role/i).first()
  if (await roleSelect.count()) {
    try {
      await roleSelect.click()
      await page.getByRole('option', { name: /viewer|auditor/i }).first().click({ timeout: 1500 })
    } catch {}
  }

  await page.getByRole('button', { name: /invite|send|submit/i }).first().click()
  await page.waitForLoadState('networkidle', { timeout: 10_000 }).catch(() => {})

  // Other endpoints should not 4xx/5xx.
  await expectNoResponseErrors(otherErrors)

  // For the invite endpoint specifically: if it failed, the body must be informative.
  if (inviteErrors.length) {
    for (const e of inviteErrors) {
      console.log(`[crud:invite] response ${e.status} ${e.url} :: ${e.body ?? ''}`)
      const body = e.body ?? ''
      expect(
        body.length > 0 && !/^internal server error$/i.test(body.trim()),
        `Invite endpoint returned opaque error: "${body}"`,
      ).toBeTruthy()
    }
  }
})
