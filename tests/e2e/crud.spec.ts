import { test, expect, type Page } from '@playwright/test'
import { signIn } from './_helpers/sign-in'

/**
 * 5 CRUD-flow tests. Each test signs in fresh.
 *
 * Design notes:
 * - These are DIAGNOSTIC tests. If a "Create"/"New" button isn't found within 3s,
 *   the test soft-skips with `test.skip()` after logging every role=button accessible
 *   name on the page. The supervisor uses these runs to discover the actual UI labels;
 *   they should not block the suite on label drift.
 * - Every test installs a `page.on('response')` collector that fails the test if any
 *   4xx/5xx fires during the flow, with URL + status + body excerpt.
 * - Entity names use `${Date.now()}` so re-runs don't collide.
 */

type ResponseError = { status: number; url: string; body?: string }

function installResponseSpy(page: Page): ResponseError[] {
  const errors: ResponseError[] = []
  page.on('response', async (r) => {
    const status = r.status()
    if (status < 400) return
    // Ignore favicon, _next static, and HMR/dev-server noise.
    const url = r.url()
    if (url.includes('/_next/') || url.endsWith('/favicon.ico')) return
    let body: string | undefined
    try {
      body = (await r.text()).slice(0, 300)
    } catch {
      body = undefined
    }
    errors.push({ status, url, body })
  })
  return errors
}

async function expectNoResponseErrors(errors: ResponseError[]): Promise<void> {
  expect(
    errors,
    errors.map((e) => `${e.status} ${e.url} :: ${e.body ?? ''}`).join('\n'),
  ).toHaveLength(0)
}

/**
 * Try to click a button that looks like "Create"/"New"/"Add". If none is found
 * within `timeout` ms, log every role=button accessible name and skip the test.
 */
async function clickCreateOrSkip(page: Page, hint: string, timeout = 3000): Promise<boolean> {
  const candidates: RegExp[] = [
    /create/i,
    /^new\b/i,
    /add\s+new/i,
    /^add\b/i,
  ]
  for (const re of candidates) {
    const btn = page.getByRole('button', { name: re }).first()
    try {
      await btn.waitFor({ state: 'visible', timeout })
      await btn.click()
      return true
    } catch {
      // try next candidate
    }
    // Also try anchor/link variants
    const link = page.getByRole('link', { name: re }).first()
    try {
      await link.waitFor({ state: 'visible', timeout: 500 })
      await link.click()
      return true
    } catch {
      // ignore
    }
  }
  // Dump button names for the supervisor to learn the correct selector.
  const allButtons = await page.getByRole('button').all()
  const names: string[] = []
  for (const b of allButtons) {
    try {
      const n = await b.textContent({ timeout: 200 })
      if (n) names.push(n.trim())
    } catch {}
  }
  const allLinks = await page.getByRole('link').all()
  const linkNames: string[] = []
  for (const l of allLinks.slice(0, 30)) {
    try {
      const n = await l.textContent({ timeout: 200 })
      if (n) linkNames.push(n.trim())
    } catch {}
  }
  console.log(`[crud:${hint}] no create button found.`)
  console.log(`  buttons: ${JSON.stringify(names)}`)
  console.log(`  links:   ${JSON.stringify(linkNames.slice(0, 30))}`)
  test.skip(true, `[crud:${hint}] No Create/New/Add button discoverable on this page — supervisor: extend selector candidates.`)
  return false
}

