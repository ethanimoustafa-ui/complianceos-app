test('crud: letter create → submit for approval → approve', async ({ page }) => {
  const errors = installResponseSpy(page)
  await signIn(page)

  // The new-letter route per HANDOFF UI — try direct first, fall back to discovery.
  await page.goto('/correspondence/letters', { waitUntil: 'networkidle', timeout: 25_000 })

  const ok = await clickCreateOrSkip(page, 'letter')
  if (!ok) return

  const subject = `Letter_${Date.now()}`
  const subjectField = page
    .getByLabel(/subject|title|name/i)
    .or(page.locator('input[type="text"]'))
    .first()
  await subjectField.fill(subject)

  const body = page.getByLabel(/body|content|message/i).first()
  if (await body.count()) {
    try {
      await body.fill(`Test letter @ ${new Date().toISOString()}`)
    } catch {}
  }

  await page.getByRole('button', { name: /save|create|submit/i }).first().click()
  await page.waitForLoadState('networkidle', { timeout: 15_000 }).catch(() => {})

  // Submit for approval (best-effort).
  const submitForApproval = page
    .getByRole('button', { name: /submit.*approv|send for approval/i })
    .first()
  if (await submitForApproval.count()) {
    await submitForApproval.click().catch(() => {})
    await page.waitForLoadState('networkidle', { timeout: 5_000 }).catch(() => {})
  }

  // Approve (best-effort loop — multiple approval steps possible).
  for (let i = 0; i < 5; i++) {
    const approve = page.getByRole('button', { name: /^approve$|approve step/i }).first()
    if (!(await approve.count())) break
    await approve.click().catch(() => {})
    await page.waitForLoadState('networkidle', { timeout: 5_000 }).catch(() => {})
  }

  await expectNoResponseErrors(errors)
})

