'use client'

import { useState, useEffect, useRef } from 'react'
import { Icon } from '@iconify/react'
import { Modal } from '@/components/ui/modal'
import { useAuthStore } from '@/stores/auth-store'
import { useTranslation } from '@/i18n'
import type { TranslationKey } from '@/i18n'
import { dicebearAvatar } from '@/lib/avatar'
import { createClient } from '@/lib/supabase/client'
import { validateFile, IMAGE_UPLOAD_RULE, IMAGE_ALLOWED_TYPES } from '@/lib/upload-validation'

// Public Storage bucket for uploaded profile photos (migration 113).
const AVATAR_BUCKET = 'avatars'

// One consistent style (DiceBear avataaars "people"), many seeds for variety.
// All generated by the DiceBear CDN — zero server storage.
const AVATAR_PRESETS = [
  'Felix', 'Sarah', 'Michael', 'Ahmed', 'Layla', 'Omar', 'Fatima', 'Hassan',
  'Nora', 'Khalid', 'Mona', 'Yusuf', 'Aria', 'Zane', 'Iris', 'Leo',
  'Maya', 'Sam', 'Remy', 'Joy', 'Luna', 'Adam', 'Hana', 'Tariq',
]

// KSA / culturally-representative presets, built from DiceBear avataaars options
// (see `dicebearAvatar` option support). DiceBear has no literal thobe/ghutra,
// so men use `turban`/business attire and women use `hijab` with abaya-toned
// (dark) clothing + dark `hatColor` (the hijab fabric) — the closest the engine
// offers. `PRO_FACE` PINS a calm, professional look on every preset: fixed
// expression (`eyes/eyebrows/mouth`) so the seed can't randomize a distressed
// face, plus `facialHairProbability=0` to guarantee clean-shaven (the enum has
// no "none" value, and the default probability would otherwise grow a beard on
// some seeds). Only skin tone and hair vary by seed.
const PRO_FACE = 'eyes=default&eyebrows=default&mouth=smile&facialHairProbability=0'
const KSA_AVATAR_PRESETS = [
  // Women — hijab (dark, professional) + abaya-toned clothing.
  `avataaars:Layla?top=hijab&hatColor=262e33&clothesColor=262e33&${PRO_FACE}`,
  `avataaars:Fatima?top=hijab&hatColor=3c4f5c&clothesColor=3c4f5c&${PRO_FACE}`,
  `avataaars:Noura?top=hijab&hatColor=25557c&clothesColor=25557c&${PRO_FACE}`,
  `avataaars:Aisha?top=hijab&hatColor=929598&clothesColor=3c4f5c&${PRO_FACE}`,
  // Men — traditional headwear (turban, light), clean-shaven, light/white attire.
  `avataaars:Khalid?top=turban&hatColor=ffffff&clothesColor=e6e6e6&${PRO_FACE}`,
  `avataaars:Abdullah?top=turban&hatColor=e6e6e6&clothesColor=ffffff&${PRO_FACE}`,
  `avataaars:Saud?top=turban&hatColor=ffffff&clothesColor=ffffff&${PRO_FACE}`,
  // Men — international / business attire, clean-shaven.
  `avataaars:Yousef?top=shortFlat&clothing=blazerAndShirt&clothesColor=25557c&${PRO_FACE}`,
  `avataaars:Faisal?top=shortCurly&clothing=blazerAndSweater&clothesColor=3c4f5c&${PRO_FACE}`,
  `avataaars:Tariq?top=theCaesar&clothing=collarAndSweater&clothesColor=929598&${PRO_FACE}`,
  // Women — international / business attire.
  `avataaars:Reem?top=straight02&clothing=blazerAndShirt&clothesColor=25557c&${PRO_FACE}`,
  `avataaars:Maha?top=bob&clothing=blazerAndSweater&clothesColor=3c4f5c&${PRO_FACE}`,
]

interface ProfileModalProps {
  isOpen: boolean
  onClose: () => void
}

export function ProfileModal({ isOpen, onClose }: ProfileModalProps) {
  const { t } = useTranslation()
  const user = useAuthStore(s => s.user)
  const updateProfile = useAuthStore(s => s.updateProfile)
  const fileInputRef = useRef<HTMLInputElement>(null)

  const [name, setName] = useState('')
  const [phone, setPhone] = useState('')
  const [avatarSeed, setAvatarSeed] = useState('Felix')
  const [customAvatar, setCustomAvatar] = useState<string | null>(null)
  const [showAvatarPicker, setShowAvatarPicker] = useState(false)
  const [isUploadingAvatar, setIsUploadingAvatar] = useState(false)
  const [avatarError, setAvatarError] = useState<string | null>(null)

  useEffect(() => {
    if (isOpen && user) {
      setName(user.name)
      setPhone(user.phone || '')
      setAvatarSeed(user.avatarSeed || 'Felix')
      setCustomAvatar(user.avatar || null)
      setShowAvatarPicker(false)
      setAvatarError(null)
    }
  }, [isOpen, user])

  const avatarSrc = customAvatar || dicebearAvatar(avatarSeed)

  const handleSave = () => {
    updateProfile({
      name,
      phone, // pass through even when blank so the number can be cleared
      avatarSeed,
      avatar: customAvatar ?? '', // '' clears the stored photo → falls back to the seed
    })
    onClose()
  }

  const handleAvatarUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0]
    if (!file || !user) return
    e.target.value = ''
    setAvatarError(null)
    setShowAvatarPicker(false)
    // Pre-check size + type so the user gets a specific, actionable message
    // BEFORE the bytes are uploaded — instead of a generic failure after the
    // 5 MB avatars bucket rejects them.
    const invalid = validateFile(file, IMAGE_UPLOAD_RULE)
    if (invalid) {
      setAvatarError(typeof invalid === 'string' ? invalid : t(invalid.key as TranslationKey, invalid.params))
      return
    }
    setIsUploadingAvatar(true)
    // Instant local preview while the upload runs.
    setCustomAvatar(URL.createObjectURL(file))
    try {
      const supabase = createClient()
      const safeName = file.name.replace(/[^A-Za-z0-9._-]/g, '_')
      const storagePath = `${user.id}/${Date.now()}-${safeName}`
      const { error: uploadError } = await supabase.storage
        .from(AVATAR_BUCKET)
        .upload(storagePath, file, {
          cacheControl: '31536000',
          upsert: true,
          contentType: file.type || 'image/png',
        })
      if (uploadError) throw uploadError
      // PUBLIC bucket → stable URL that survives reload and renders everywhere.
      const { data: publicData } = supabase.storage.from(AVATAR_BUCKET).getPublicUrl(storagePath)
      if (!publicData?.publicUrl) throw new Error('No public URL')
      setCustomAvatar(publicData.publicUrl)
    } catch (err) {
      console.error('[ProfileModal] avatar upload failed:', err)
      setAvatarError(t('upload.failed' as TranslationKey))
      setCustomAvatar(user.avatar || null)
    } finally {
      setIsUploadingAvatar(false)
    }
  }

  const handleSelectPreset = (seed: string) => {
    setAvatarSeed(seed)
    setCustomAvatar(null)
    setShowAvatarPicker(false)
  }

  if (!user) return null

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title={t('sidebar.editProfile')}
      size="lg"
    >
      <div className="space-y-6">
        {/* Avatar Section */}
        <div className="flex flex-col items-center gap-4 pb-6 border-b border-slate-200">
          <div
            className="relative group cursor-pointer"
            onClick={() => fileInputRef.current?.click()}
          >
            <img
              src={avatarSrc}
              alt="Profile"
              className="w-24 h-24 rounded-full border-4 border-slate-200"
            />
            <div className="absolute inset-0 bg-slate-900/60 rounded-full opacity-0 group-hover:opacity-100 transition-opacity flex items-center justify-center">
              <Icon icon="lucide:camera" className="text-white text-2xl" />
            </div>
            {isUploadingAvatar && (
              <div className="absolute inset-0 bg-slate-900/60 rounded-full flex items-center justify-center">
                <Icon icon="lucide:loader-2" className="text-white text-2xl animate-spin" />
              </div>
            )}
          </div>
          <input
            ref={fileInputRef}
            type="file"
            accept={IMAGE_ALLOWED_TYPES.join(',')}
            className="hidden"
            onChange={handleAvatarUpload}
          />
          <div className="flex gap-3">
            <button
              type="button"
              onClick={() => fileInputRef.current?.click()}
              className="text-sm font-bold text-emerald-600 hover:text-emerald-700 flex items-center gap-2 cursor-pointer"
            >
              <Icon icon="lucide:upload" className="text-lg" />
              {t('sidebar.uploadPhoto')}
            </button>
            <button
              type="button"
              onClick={() => setShowAvatarPicker(!showAvatarPicker)}
              className="text-sm font-bold text-blue-600 hover:text-blue-700 flex items-center gap-2 cursor-pointer"
            >
              <Icon icon="lucide:grid-3x3" className="text-lg" />
              {t('sidebar.chooseAvatar')}
            </button>
          </div>

          {avatarError && (
            <p className="text-xs font-semibold text-rose-600">{avatarError}</p>
          )}

          {showAvatarPicker && (
            <div className="w-full mt-4 p-4 bg-slate-50 rounded-xl border border-slate-200 space-y-5">
              {/* KSA / culturally-representative set first. */}
              <div>
                <p className="text-xs font-bold text-slate-700 uppercase mb-3">{t('sidebar.avatarKsa')}</p>
                <div className="grid grid-cols-6 gap-3">
                  {KSA_AVATAR_PRESETS.map((seed) => (
                    <button
                      key={seed}
                      type="button"
                      onClick={() => handleSelectPreset(seed)}
                      className={`w-12 h-12 rounded-full border-2 transition-all overflow-hidden cursor-pointer ${
                        avatarSeed === seed ? 'border-emerald-500 ring-2 ring-emerald-500/30' : 'border-slate-200 hover:border-emerald-500'
                      }`}
                    >
                      <img src={dicebearAvatar(seed)} alt="" className="w-full h-full" />
                    </button>
                  ))}
                </div>
              </div>
              {/* Existing classic seeds, kept as-is. */}
              <div>
                <p className="text-xs font-bold text-slate-700 uppercase mb-3">{t('sidebar.avatarClassic')}</p>
                <div className="grid grid-cols-6 gap-3">
                  {AVATAR_PRESETS.map((seed) => (
                    <button
                      key={seed}
                      type="button"
                      onClick={() => handleSelectPreset(seed)}
                      className={`w-12 h-12 rounded-full border-2 transition-all overflow-hidden cursor-pointer ${
                        avatarSeed === seed ? 'border-emerald-500 ring-2 ring-emerald-500/30' : 'border-slate-200 hover:border-emerald-500'
                      }`}
                    >
                      <img src={dicebearAvatar(seed)} alt={seed} className="w-full h-full" />
                    </button>
                  ))}
                </div>
              </div>
            </div>
          )}
        </div>

        {/* Form Fields */}
        <div>
          <label className="text-xs font-bold text-slate-700 uppercase mb-2 block">
            {t('sidebar.fullName')}
          </label>
          <input
            type="text"
            value={name}
            onChange={(e) => setName(e.target.value)}
            className="w-full px-4 py-3 border border-slate-200 rounded-lg text-sm focus:outline-none focus:ring-2 focus:ring-emerald-500"
          />
        </div>

        <div>
          <label className="text-xs font-bold text-slate-700 uppercase mb-2 block">
            {t('sidebar.emailAddress')}
          </label>
          <input
            type="email"
            value={user.email}
            readOnly
            title={t('sidebar.emailReadOnlyHint' as TranslationKey)}
            className="w-full px-4 py-3 border border-slate-200 rounded-lg text-sm bg-slate-50 text-slate-500 cursor-not-allowed"
          />
        </div>

        <div>
          <label className="text-xs font-bold text-slate-700 uppercase mb-2 block">
            {t('sidebar.phoneNumber')}
          </label>
          <input
            type="tel"
            value={phone}
            onChange={(e) => setPhone(e.target.value)}
            className="w-full px-4 py-3 border border-slate-200 rounded-lg text-sm focus:outline-none focus:ring-2 focus:ring-emerald-500"
          />
        </div>

        <div className="grid grid-cols-2 gap-4">
          <div>
            <label className="text-xs font-bold text-slate-700 uppercase mb-2 block">
              {t('sidebar.department')}
            </label>
            <input
              type="text"
              value={user.department}
              readOnly
              className="w-full px-4 py-3 border border-slate-200 rounded-lg text-sm bg-slate-50 text-slate-500 cursor-not-allowed"
            />
          </div>
          <div>
            <label className="text-xs font-bold text-slate-700 uppercase mb-2 block">
              {t('sidebar.role')}
            </label>
            <input
              type="text"
              value={user.role}
              readOnly
              className="w-full px-4 py-3 border border-slate-200 rounded-lg text-sm bg-slate-50 text-slate-500 cursor-not-allowed capitalize"
            />
          </div>
        </div>

        {/* Footer */}
        <div className="flex gap-3 mt-8">
          <button
            onClick={handleSave}
            disabled={isUploadingAvatar}
            className="flex-1 bg-emerald-600 text-white py-3 rounded-lg font-bold hover:bg-emerald-700 transition-colors flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50 disabled:cursor-not-allowed"
          >
            <Icon icon="lucide:check" className="text-lg" />
            {t('sidebar.save')}
          </button>
          <button
            onClick={onClose}
            className="px-6 bg-slate-100 text-slate-700 py-3 rounded-lg font-bold hover:bg-slate-200 transition-colors cursor-pointer"
          >
            {t('common.cancel')}
          </button>
        </div>
      </div>
    </Modal>
  )
}
