// Shared LaTeX building blocks for the executive "report" family (compliance,
// observations, risks, audits). Distinct from the SAMA letter: these have a
// cover page, section styling, brand header/footer, and pgfplots charts.
//
// All helpers return `.tex` fragments. The renderer container compiles them.
// Locale-aware: English (LTR, Latin Modern Sans) or Arabic (RTL, polyglossia +
// Amiri). Charts are numeric, so they read the same in both directions.

import { escapeLatex } from './sanitize'
import { LETTERHEAD_PNG_B64, GPTW_BADGE_PNG_B64 } from './assets'

const RAW = String.raw

export type LatexLocale = 'en' | 'ar'

/** filename -> base64 PNG; spread into every report's `assets`. */
export const REPORT_ASSETS: Record<string, string> = {
  'letterhead.png': LETTERHEAD_PNG_B64,
  'badge.png': GPTW_BADGE_PNG_B64,
}

